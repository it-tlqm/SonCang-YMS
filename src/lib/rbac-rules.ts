/**
 * Kiểm tra xem người dùng có quyền thực hiện hành động hay không.
 * Nếu đã có danh sách userPermissions (từ Supabase / Real Mode), kiểm tra chặt chẽ trên đó,
 * TUYỆT ĐỐI KHÔNG fallback sang danh sách hardcoded (ON-11).
 * Fallback theo vai trò tĩnh chỉ được phép khi userPermissions là undefined (Demo Mode).
 */
export function hasPermission(
  role: RoleCode | null | undefined,
  permissionCode: string,
  userPermissions?: string[]
): boolean {
  if (userPermissions !== undefined) {
    return userPermissions.includes(permissionCode);
  }
  if (!role) return false;
  const perms = ROLE_PERMISSIONS_V5[role];
  if (!perms) return false;
  return perms.includes(permissionCode);
}

